def build_hand_prompt() -> str:
    """Увеличенный вырез ручки: буквы крупнее, печатный бланк вокруг не переписывать."""
    return (
        "Это увеличенный фрагмент текста, написанного от руки ручкой.\n"
        "Перепиши только буквы и цифры ручки, слева направо, как написано. "
        "Печатный бланк вокруг не переписывай. Неразборчивое слово — [...]. "
        "Не исправляй и не дописывай. Верни только этот текст, без пояснений."
    )


def build_page_prompt(kind: str, page: int, *, markers: bool = False, part: tuple[int, int] | None = None) -> str:
    """Промпт для страницы-скана PDF: VLM — основной способ извлечь текст, а не подпись к картинке."""
    task = _PAGE_TASK.get(kind, _PAGE_TASK["text_scan"])
    piece = (
        f"Это часть {part[0]} из {part[1]} страницы (полоса сверху вниз): перепиши только то, что видно на ней; "
        "строку, обрезанную краем полосы, не дописывай.\n"
        if part
        else ""
    )
    return (
        f"Это скан страницы {page} документа (PDF без текстового слоя).\n{task}\n{piece}"
        f"{_MARKERS if markers else ''}"
        "Не выдумывай текст, которого нет на изображении; нечитаемое место — «[неразборчиво]».\n"
        "Ответ строго в формате из трёх разделов:\n"
        "Описание: тип страницы (1 предложение).\n"
        "Текст с изображения: (полный Markdown страницы)\n"
        "Анализ: о чём страница (1–2 предложения)."
    )


def build_table_retry_prompt(page: int) -> str:
    """Вторая попытка по вырезу таблицы: без разделов «Описание/Анализ», только сама таблица."""
    return f"Это вырез таблицы со скана страницы {page} документа.\n{_PAGE_TASK['table_retry']}"


def parse_sections(text: str) -> dict[str, str]:
    """{'Описание': …, 'Текст с изображения': …, 'Анализ': …}; без меток — всё в «Описание»."""
    matches = list(_LABEL.finditer(text))
    if not matches:
        return {"Описание": text.strip()}
    sections: dict[str, str] = {}
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        value = text[m.end() : end].strip()
        if value and value.lower().strip(" .«»\"") not in ("нет", "-", "—"):
            sections.setdefault(m.group(1), value)
    return sections
